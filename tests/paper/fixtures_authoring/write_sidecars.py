def main() -> int:
    for relpath, payload in sorted(SIDECARS.items()):
        docx_path = FIXTURES_DIR / relpath
        assert docx_path.is_file(), f"fixture missing for sidecar: {relpath}"
        sidecar_file = docx_path.with_suffix(".json")
        sidecar_file.write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        print(f"wrote {sidecar_file.relative_to(FIXTURES_DIR)}")
    docx_count = len(list(FIXTURES_DIR.rglob("*.docx")))
    assert docx_count == len(SIDECARS), (
        f"{docx_count} fixtures on disk but {len(SIDECARS)} sidecars defined"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

def sidecar(
    relpath: str,
    provenance: Dict[str, str],
    features: List[str],
    ground_truth: Dict[str, Any],
) -> Dict[str, Any]:
    return {
        "fixture": Path(relpath).name,
        "provenance": provenance,
        "features": features,
        "ground_truth": ground_truth,
        "verified_by": VERIFIED_BY,
        "date": SIDECAR_DATE,
    }


